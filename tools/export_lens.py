"""Export the lens and our word library to TypeScript for the chat mod.

    python tools/export_lens.py [out.ts]

The mod has no Node or Python, so the lens (patterns, colors, cues) and the word library
(lenses/library.toml, with every verb form worked out) are baked into .ts files beside each other.
Run this again whenever lenses/default.toml or lenses/library.toml changes.
"""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from synesthetic import library  # noqa: E402

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "chat-mod" / "synesthetic-chat" / "hooks" / "lens.ts"


def _colors(c: dict) -> dict:
    return {
        "dark": c["dark"],
        "light": c["light"],
        "cb_dark": c.get("cb_dark", c["dark"]),
        "cb_light": c.get("cb_light", c["light"]),
    }


def main(out: Path) -> None:
    data = tomllib.loads((ROOT / "lenses" / "default.toml").read_text(encoding="utf-8"))
    cats = []
    grammar = []
    for c in data["category"]:
        layer = c.get("layer", "content")
        cues = {"font": c.get("font", "normal"), "weight": c.get("weight", 0), "underline": c.get("underline", "none"),
                "case": "upper" if c.get("case") == "upper" else "normal"}
        if layer == "grammar":
            kinds = [k for k, pos in library.KIND_POS.items() if pos in c.get("pos", ())]
            if kinds:  # drawn in chat from the word library, with no language model
                grammar.append({"name": c["name"], "label": c.get("label", c["name"]), "kind": kinds[0],
                                "colors": _colors(c), **cues})
            continue
        if layer != "content":
            continue  # meaning needs a model call: not in chat
        cats.append(
            {
                "name": c["name"],
                "label": c.get("label", c["name"]),
                "priority": c.get("priority", 50),
                "flags": c.get("flags", ""),
                "patterns": c["patterns"],
                "colors": _colors(c),
                **cues,
                "defaultOff": bool(c.get("default_off", False)),
            }
        )
    src = (
        "// GENERATED by tools/export_lens.py from lenses/default.toml. Do not edit by hand.\n"
        "export type LensCategory = {\n"
        "  name: string\n  label: string\n  priority: number\n  flags: string\n  patterns: string[]\n"
        "  colors: { dark: string; light: string; cb_dark: string; cb_light: string }\n"
        "  font: string\n  weight: number\n  underline: string\n  case: string\n  defaultOff: boolean\n}\n\n"
        f"export const LENS: LensCategory[] = {json.dumps(cats, indent=2, ensure_ascii=False)}\n\n"
        "// The grammar looks: tint and letter shape for the words the library names.\n"
        "export type GrammarCategory = {\n"
        "  name: string\n  label: string\n  kind: string\n"
        "  colors: { dark: string; light: string; cb_dark: string; cb_light: string }\n"
        "  font: string\n  weight: number\n  underline: string\n  case: string\n}\n\n"
        f"export const GRAMMAR: GrammarCategory[] = {json.dumps(grammar, indent=2, ensure_ascii=False)}\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src, encoding="utf-8")
    print(f"wrote {out} ({len(cats)} categories, {len(grammar)} grammar looks)")

    lib = library.load_library()
    classes: dict[str, list[str]] = {}
    for word, cls in lib.words.items():
        classes.setdefault(cls, []).append(word)
    words = {k: " ".join(sorted(v)) for k, v in sorted(classes.items())}
    data_out = out.with_name("library-data.ts")
    data_out.write_text(
        "// GENERATED by tools/export_lens.py from lenses/library.toml. Do not edit by hand.\n"
        "// Word class -> its words, space separated. The classes are explained in library.ts.\n"
        f"export const WORD_CLASSES: Record<string, string> = {json.dumps(words, indent=2, ensure_ascii=False)}\n\n"
        "// The owner's own words and phrases: the look they always take, or skip.\n"
        f"export const PINS: Record<string, string> = {json.dumps(lib.pins, indent=2, ensure_ascii=False)}\n\n"
        f"export const PHRASES: Array<[string, string]> = {json.dumps(lib.phrases, ensure_ascii=False)}\n",
        encoding="utf-8",
    )
    print(f"wrote {data_out} ({len(lib.words)} words)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT)
