"""Export the content-type lens to TypeScript for the chat mod.

    python tools/export_lens.py [out.ts]

The mod has no Node or Python, so the lens (patterns, colors, cues) is baked into a .ts file.
Run this again whenever lenses/default.toml changes.
"""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "chat-mod" / "synesthetic-chat" / "hooks" / "lens.ts"


def main(out: Path) -> None:
    data = tomllib.loads((ROOT / "lenses" / "default.toml").read_text(encoding="utf-8"))
    cats = []
    for c in data["category"]:
        if c.get("layer", "content") != "content":
            continue  # grammar needs an NLP model and meaning needs a model call: not in chat
        cats.append(
            {
                "name": c["name"],
                "label": c.get("label", c["name"]),
                "priority": c.get("priority", 50),
                "flags": c.get("flags", ""),
                "patterns": c["patterns"],
                "colors": {
                    "dark": c["dark"],
                    "light": c["light"],
                    "cb_dark": c.get("cb_dark", c["dark"]),
                    "cb_light": c.get("cb_light", c["light"]),
                },
                "font": c.get("font", "normal"),
                "weight": c.get("weight", 0),
                "underline": c.get("underline", "none"),
                "defaultOff": bool(c.get("default_off", False)),
            }
        )
    src = (
        "// GENERATED by tools/export_lens.py from lenses/default.toml. Do not edit by hand.\n"
        "export type LensCategory = {\n"
        "  name: string\n  label: string\n  priority: number\n  flags: string\n  patterns: string[]\n"
        "  colors: { dark: string; light: string; cb_dark: string; cb_light: string }\n"
        "  font: string\n  weight: number\n  underline: string\n  defaultOff: boolean\n}\n\n"
        f"export const LENS: LensCategory[] = {json.dumps(cats, indent=2, ensure_ascii=False)}\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src, encoding="utf-8")
    print(f"wrote {out} ({len(cats)} categories)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT)
